package org.iz.navigation.navigation

import java.io.File
import org.iz.navigation.weather.*
import org.json.JSONArray
import org.json.JSONObject
import org.junit.Assert.*
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder

class NavigationRouteExclusionCacheTest {
    @get:Rule val temp = TemporaryFolder()
    private val areas = listOf(
        RouteAvoidArea(-0.02, -0.02, 0.02, 0.02),
        RouteAvoidArea(0.1, 0.1, 0.14, 0.14),
        RouteAvoidArea(-0.02, 179.94, 0.02, 179.98),
    )
    private fun route(avoid: List<RouteAvoidArea> = areas): PlannedRoute {
        val a = WeatherCoordinate(40.0, 29.0)
        val b = WeatherCoordinate(40.01, 29.01)
        return PlannedRoute("original-route", listOf(RouteStop("Start", a), RouteStop("Destination", b)),
            listOf(RouteVertex(a, 0.0), RouteVertex(b, 100.0)), 1200.0, 100.0, 123L,
            selectionLocked = true, providerWarnings = listOf("Provider warning"), avoidAreas = avoid)
    }
    // Independent pre-v4 fixture, rather than a payload generated by the writer under test.
    private fun payload(version: Int) = JSONObject("""{
        "version":$version,"id":"historical-route",
        "stops":[{"label":"Start","lat":40,"lon":29},{"label":"Destination","lat":40.01,"lon":29.01}],
        "vertices":[{"lat":40,"lon":29,"elapsed":0},{"lat":40.01,"lon":29.01,"elapsed":100}],
        "distance":1200,"duration":100,"createdAt":123
    }""")
    private fun areaJson(area: RouteAvoidArea) = JSONObject().put("south", area.south)
        .put("west", area.west).put("north", area.north).put("east", area.east)
    private fun saved(dir: File) = File(dir, "route.json")

    @Test fun lastAndPreparedRouteDirectoriesKeepAllExclusionsAcrossNewCacheInstances() {
        val expected = route()
        for (name in listOf("last-route", "prepared-route")) {
            val dir = temp.newFolder(name)
            NavigationRouteCache(dir).write(expected)
            val restored = NavigationRouteCache(dir).read()!!
            assertEquals(expected, restored)
            assertEquals(areas, restored.avoidAreas)
            assertEquals(expected.stops.last(), restored.stops.last())
            val json = JSONObject(saved(dir).readText())
            assertEquals(5, json.getInt("version"))
            assertEquals(3, json.getJSONArray("avoidAreas").length())
        }
    }

    @Test fun newFormatWritesAnExplicitEmptyExclusionArray() {
        val dir = temp.newFolder()
        val expected = route(emptyList())
        NavigationRouteCache(dir).write(expected)
        val json = JSONObject(saved(dir).readText())
        assertEquals(5, json.getInt("version"))
        assertEquals(0, json.getJSONArray("avoidAreas").length())
        assertEquals(expected, NavigationRouteCache(dir).read())
    }

    @Test fun versionsOneThroughThreeRemainReadableWithNoExclusions() {
        val dir = temp.newFolder()
        for (version in 1..3) {
            saved(dir).writeText(payload(version).toString())
            val restored = NavigationRouteCache(dir).read()!!
            assertEquals("historical-route", restored.id)
            assertEquals(emptyList<RouteAvoidArea>(), restored.avoidAreas)
            assertEquals(WeatherCoordinate(40.01, 29.01), restored.stops.last().coordinate)
        }
    }

    @Test fun independentVersionFourPayloadRestoresEveryBoundAndAreaOrder() {
        val dir = temp.newFolder()
        saved(dir).writeText(payload(4).put("avoidAreas", JSONArray().apply {
            areas.forEach { put(areaJson(it)) }
        }).toString())
        val restored = NavigationRouteCache(dir).read()
        assertNotNull("A valid v4 route with exclusions must restore", restored)
        assertEquals(areas, restored!!.avoidAreas)
        assertEquals("historical-route", restored.id)
    }

    @Test fun malformedOrUnboundedVersionFourExclusionsAreRejectedInsteadOfDropped() {
        val dir = temp.newFolder()
        val malformed = listOf(
            payload(4), // Missing v4 constraints cannot silently become an unconstrained route.
            payload(4).put("avoidAreas", JSONObject.NULL),
            payload(4).put("avoidAreas", JSONObject()),
            payload(4).put("avoidAreas", JSONArray().put(JSONObject.NULL)),
            payload(4).put("avoidAreas", JSONArray().put(JSONObject().put("south", 0))),
            payload(4).put("avoidAreas", JSONArray().apply { repeat(4) { put(areaJson(areas.first())) } }),
            payload(4).put("avoidAreas", JSONArray().put(areaJson(areas.first()).put("north", -0.03))),
            payload(4).put("avoidAreas", JSONArray().put(areaJson(areas.first()).put("east", 0.3))),
            payload(4).put("avoidAreas", JSONArray().put(areaJson(areas.first()).put("north", 90))),
        )
        malformed.forEachIndexed { index, json ->
            saved(dir).writeText(json.toString())
            assertNull("Invalid exclusion payload $index must not restore", NavigationRouteCache(dir).read())
        }
    }

    @Test fun writeRechecksTheAreaBoundBeforeReplacingAnExistingCache() {
        val dir = temp.newFolder()
        val cache = NavigationRouteCache(dir)
        val previous = route(emptyList())
        cache.write(previous)
        val previousBytes = saved(dir).readBytes()
        val mutableAreas = mutableListOf(areas.first())
        val candidate = route(mutableAreas)
        repeat(3) { mutableAreas.add(areas.last()) }
        try {
            cache.write(candidate)
            fail("A mutated list exceeding three areas must be rejected before any disk replacement")
        } catch (_: IllegalArgumentException) { }
        assertArrayEquals(previousBytes, saved(dir).readBytes())
        assertEquals(previous, NavigationRouteCache(dir).read())
        assertFalse(File(dir, "route.json.tmp").exists())
    }

    @Test fun tomTomRoutesStillClearPersistentGeometryEvenWhenTheyHaveExclusions() {
        val dir = temp.newFolder()
        val cache = NavigationRouteCache(dir)
        cache.write(route())
        cache.write(route().copy(provider = RouteProvider.TOMTOM))
        assertNull(NavigationRouteCache(dir).read())
        assertFalse(saved(dir).exists())
        assertFalse(File(dir, "route.json.tmp").exists())
    }
}
